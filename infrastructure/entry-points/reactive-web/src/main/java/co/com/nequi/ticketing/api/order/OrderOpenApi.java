package co.com.nequi.ticketing.api.order;

import co.com.nequi.ticketing.api.commons.ErrorEnvelope;
import co.com.nequi.ticketing.api.commons.Meta;
import co.com.nequi.ticketing.api.order.dto.request.PlaceOrderRequestDto;
import co.com.nequi.ticketing.api.order.dto.response.OrderResponseDto;
import co.com.nequi.ticketing.api.order.dto.response.PlaceOrderResponseDto;
import io.swagger.v3.oas.annotations.enums.ParameterIn;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.experimental.UtilityClass;
import org.springdoc.core.fn.builders.operation.Builder;

import java.util.UUID;

import static org.springdoc.core.fn.builders.apiresponse.Builder.responseBuilder;
import static org.springdoc.core.fn.builders.parameter.Builder.parameterBuilder;
import static org.springdoc.core.fn.builders.requestbody.Builder.requestBodyBuilder;

/**
 * OpenAPI documentation of the order routes, equivalent to the feature contract.
 */
@UtilityClass
public class OrderOpenApi {

    private static final String TAG = "Orders";

    public static void placeOrder(Builder operation) {
        operation.operationId("placeOrder")
                .tag(TAG)
                .summary("Reserve 1 to 6 tickets of an active event for 10 minutes and accept the order")
                .description("The tickets are reserved in the same instant the order is accepted. The response "
                        + "does not wait for the payment. Repeating the request with the same Idempotency-Key and "
                        + "body returns exactly the original outcome")
                .parameter(customerIdParameter())
                .parameter(parameterBuilder().name("Idempotency-Key").in(ParameterIn.HEADER).required(true)
                        .description("Generated by the client once per purchase intent and reused on every retry; "
                                + "valid 24 h per customer")
                        .implementation(UUID.class))
                .requestBody(requestBodyBuilder().required(true).implementation(PlaceOrderRequestDto.class))
                .response(responseBuilder().responseCode("202")
                        .description("Order accepted and tickets reserved (meta.code TKS0003)")
                        .implementation(PlaceOrderEnvelope.class))
                .response(error("400", "TKT0001 validation error (quantity, eventId, missing or invalid "
                        + "X-Customer-Id), TKT0002 invalid JSON, TKT0003 empty body, TKT0004 missing or invalid "
                        + "Idempotency-Key"))
                .response(error("404", "TKB0001 event not found"))
                .response(error("409", "TKB0003 tickets sold out, TKB0006 the original request with this key is "
                        + "still in progress, TKB0007 event not active or already started"))
                .response(error("422", "TKB0004 ticket limit per customer and event exceeded, TKB0005 "
                        + "Idempotency-Key reused with a different body"))
                .response(error("500", "TKT0005 database error, TKT0009 unexpected error (the key is released; "
                        + "a retry tries again)"));
    }

    public static void getOrder(Builder operation) {
        operation.operationId("getOrder")
                .tag(TAG)
                .summary("Get an order of the calling customer, with the status of each ticket")
                .description("Strongly consistent read. The order shows EXPIRED as soon as its expiration time "
                        + "is reached. An order of another customer answers exactly like a missing one")
                .parameter(customerIdParameter())
                .parameter(parameterBuilder().name("orderId").in(ParameterIn.PATH).required(true)
                        .implementation(UUID.class))
                .response(responseBuilder().responseCode("200").description("Order (meta.code TKS0001)")
                        .implementation(OrderEnvelope.class))
                .response(error("400", "TKT0001 orderId is not a UUID or X-Customer-Id is missing or invalid"))
                .response(error("404", "TKB0002 order not found or owned by another customer"))
                .response(error("500", "TKT0005, TKT0009"));
    }

    private static org.springdoc.core.fn.builders.parameter.Builder customerIdParameter() {
        return parameterBuilder().name("X-Customer-Id").in(ParameterIn.HEADER).required(true)
                .description("Customer identity until feature 004 (JWT subject)").implementation(UUID.class);
    }

    private static org.springdoc.core.fn.builders.apiresponse.Builder error(String code, String description) {
        return responseBuilder().responseCode(code).description(description).implementation(ErrorEnvelope.class);
    }

    @Schema(name = "PlaceOrderEnvelope")
    record PlaceOrderEnvelope(Meta meta, PlaceOrderResponseDto data) {
    }

    @Schema(name = "OrderEnvelope")
    record OrderEnvelope(Meta meta, OrderResponseDto data) {
    }
}
